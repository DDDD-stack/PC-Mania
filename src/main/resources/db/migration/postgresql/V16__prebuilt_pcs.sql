-- Prebuilt PCs. A prebuilt is composed of components rather than described in free text, so the site
-- can filter by GPU and RAM and the assistant can later answer "which PC has a 3060 Ti".
INSERT INTO category (name_sq, slug, sort_order, icon_class, is_visible, is_out_of_stock, catalog_slug)
SELECT 'PC të gatshëm', 'pc-te-gatshem', COALESCE(MAX(sort_order), 0) + 1, 'bi-pc-display', TRUE, FALSE, 'prebuilt'
FROM category
HAVING NOT EXISTS (SELECT 1 FROM category WHERE catalog_slug = 'prebuilt' OR slug = 'pc-te-gatshem');

CREATE TABLE prebuilt_spec (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT        NOT NULL UNIQUE,
    cpu_name            VARCHAR(120),
    cpu_cores           INT,
    cpu_threads         INT,
    gpu_catalog_id      BIGINT,
    -- the GPU's name when it is not in the catalogue
    gpu_name_override   VARCHAR(120),
    ram_gb              INT,
    ram_speed_mhz       INT,
    ram_config          VARCHAR(40),
    storage_primary     VARCHAR(120),
    storage_secondary   VARCHAR(120),
    psu_watts           INT,
    psu_brand           VARCHAR(80),
    motherboard_model   VARCHAR(120),
    case_model          VARCHAR(120),
    os_installed        BOOLEAN       NOT NULL DEFAULT FALSE,
    os_name             VARCHAR(80),
    -- measured under load: the main trust signal the shop sells on, so structured, not prose
    load_temp_cpu_c     INT,
    load_temp_gpu_c     INT,
    tested_at           DATE,
    notes_sq            TEXT,
    CONSTRAINT fk_prebuilt_product FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE CASCADE,
    CONSTRAINT fk_prebuilt_gpu FOREIGN KEY (gpu_catalog_id) REFERENCES spec_catalog_entry (id) ON DELETE SET NULL
);

CREATE INDEX ix_prebuilt_gpu ON prebuilt_spec (gpu_catalog_id);

