-- The generic autofill catalogue: one row per known model in any category ("gpu", "cpu", "ram", ...),
-- with the template field values it pre-fills as JSON keyed by field_key. Optional per category: a
-- category with no rows here still has its full template for manual entry.
--
-- GPU rows mirror gpu_catalog, which stays the assistant's source of truth. They are copied (and kept
-- in step) by the application at startup and whenever a gpu_catalog row is edited, because the
-- repeatable seed R__Seed_gpu_catalog only fills gpu_catalog after every versioned migration has run.
CREATE TABLE spec_catalog_entry (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_slug   VARCHAR(40)   NOT NULL,
    name            VARCHAR(160)  NOT NULL,
    -- comma-separated search terms, matched alongside the name
    aliases         VARCHAR(500),
    spec_json       JSONB         NOT NULL DEFAULT '{}'::jsonb,
    -- false = estimated values that still need checking against the maker's sheet
    verified        BOOLEAN       NOT NULL DEFAULT FALSE,
    gpu_catalog_id  BIGINT        UNIQUE,
    CONSTRAINT fk_spec_catalog_gpu FOREIGN KEY (gpu_catalog_id) REFERENCES gpu_catalog (id) ON DELETE CASCADE
);

CREATE INDEX ix_spec_catalog_category ON spec_catalog_entry (category_slug);

