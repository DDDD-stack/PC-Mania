-- Combo deals. A combo only references its products - name, price and photos are always read live
-- from them - and whether it is shown is decided by a query condition (every member AVAILABLE, i.e.
-- ACTIVE with enough units), never by a stored flag that could go stale.
CREATE TABLE combo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(160)  NOT NULL UNIQUE,
    title_sq         VARCHAR(200)  NOT NULL,
    subtitle_sq      VARCHAR(300),
    combo_price_lek  INT           NOT NULL,
    is_active        BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order       INT           NOT NULL DEFAULT 0,
    starts_at        TIMESTAMP,
    ends_at          TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL
);

CREATE TABLE combo_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id    BIGINT  NOT NULL,
    product_id  BIGINT  NOT NULL,
    quantity    INT     NOT NULL DEFAULT 1,
    CONSTRAINT fk_combo_item_combo FOREIGN KEY (combo_id) REFERENCES combo (id) ON DELETE CASCADE,
    -- a product in a combo cannot be deleted; it can still be hidden or sold, which hides the combo
    CONSTRAINT fk_combo_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT uq_combo_item UNIQUE (combo_id, product_id)
);

CREATE INDEX ix_combo_item_product ON combo_item (product_id);

-- What was bought as a bundle. Not a foreign key: deleting a combo later must not touch old orders.
ALTER TABLE orders ADD COLUMN combo_id BIGINT;
ALTER TABLE orders ADD COLUMN combo_title_snapshot VARCHAR(200);

-- Like every table (see V6__supabase_hardening.sql).
ALTER TABLE combo      ENABLE ROW LEVEL SECURITY;
ALTER TABLE combo_item ENABLE ROW LEVEL SECURITY;
