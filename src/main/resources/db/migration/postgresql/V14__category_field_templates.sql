-- Category field templates: which spec fields a category's products have. The admin product form
-- renders its spec inputs from these rows, and the values land in product_spec keyed by field_key.
-- Kept separate on purpose from the autofill catalogue (V15): every category has a template from
-- day one, while a catalogue to pre-fill it is optional and grows over time.

-- Which autofill catalogue a category draws on ("gpu", "cpu", ...). Site slugs are Albanian and
-- can be changed by hand, so the catalogue key is its own column.
ALTER TABLE category ADD COLUMN catalog_slug VARCHAR(40);

