-- Products entered before templates existed carry display labels as spec keys ("VRAM: 12 GB").
-- Move the GPU ones that map cleanly onto the template, so old and new listings share one filter.
-- Anything that does not match the exact "<number> <unit>" shape is left as it is.
UPDATE product_spec s SET spec_key = 'vram_gb', spec_value = regexp_replace(spec_value, '^\s*(\d+)\s*GB\s*$', '\1')
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
  AND s.spec_key = 'VRAM' AND s.spec_value ~ '^\s*\d+\s*GB\s*$'
  AND NOT EXISTS (SELECT 1 FROM product_spec o WHERE o.product_id = s.product_id AND o.spec_key = 'vram_gb');

UPDATE product_spec s SET spec_key = 'memory_type'
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
  AND s.spec_key = 'Tipi i memories'
  AND NOT EXISTS (SELECT 1 FROM product_spec o WHERE o.product_id = s.product_id AND o.spec_key = 'memory_type');

UPDATE product_spec s SET spec_key = 'tdp_watts', spec_value = regexp_replace(spec_value, '^\s*(\d+)\s*W\s*$', '\1')
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
  AND s.spec_key = 'TDP' AND s.spec_value ~ '^\s*\d+\s*W\s*$'
  AND NOT EXISTS (SELECT 1 FROM product_spec o WHERE o.product_id = s.product_id AND o.spec_key = 'tdp_watts');

UPDATE product_spec s SET spec_key = 'psu_min_watts', spec_value = regexp_replace(spec_value, '^\s*(\d+)\s*W\s*$', '\1')
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
  AND s.spec_key = 'PSU minimale' AND s.spec_value ~ '^\s*\d+\s*W\s*$'
  AND NOT EXISTS (SELECT 1 FROM product_spec o WHERE o.product_id = s.product_id AND o.spec_key = 'psu_min_watts');

UPDATE product_spec s SET spec_key = 'pcie_connectors'
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
  AND s.spec_key = 'Konektorët'
  AND NOT EXISTS (SELECT 1 FROM product_spec o WHERE o.product_id = s.product_id AND o.spec_key = 'pcie_connectors');

UPDATE product_spec s SET spec_key = 'length_mm', spec_value = regexp_replace(spec_value, '^\s*(\d+)\s*mm\s*$', '\1')
FROM product p WHERE s.product_id = p.id AND p.category_slug = 'karta-grafike'
