SELECT p.slug, p.id FROM product p
WHERE p.slug = 'motherboard-msi-a520m-tomawhok'
  AND NOT EXISTS (SELECT 1 FROM product o WHERE o.slug = 'motherboard-msi-a520m-a-pro');

UPDATE product SET slug = 'motherboard-msi-a520m-a-pro'
WHERE slug = 'motherboard-msi-a520m-tomawhok'
  AND NOT EXISTS (SELECT 1 FROM product o WHERE o.slug = 'motherboard-msi-a520m-a-pro');

