-- Search: per-category titles, descriptions and intro text, a hand-written meta description per
-- product, and a history of product slugs so a renamed product's old address answers with a 301.

ALTER TABLE category ADD COLUMN meta_title VARCHAR(120);
ALTER TABLE category ADD COLUMN meta_description VARCHAR(300);
-- Sanitised on save to p, strong, em, ul, ol, li and a.
ALTER TABLE category ADD COLUMN intro_html TEXT;

ALTER TABLE product ADD COLUMN meta_description VARCHAR(300);

CREATE TABLE product_slug_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_slug    VARCHAR(220) NOT NULL UNIQUE,
    product_id  BIGINT       NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_slug_history_product FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE CASCADE
);

CREATE INDEX ix_slug_history_product ON product_slug_history (product_id);

